// Runs the Mongolian evaluation set through the real handler (catalogue mode,
// no model) on a fresh seeded database. Every case must pass; with
// ASSISTANT_EVAL_REPORT=1 the results are also written to docs/assistant/EVAL.md
// and EVAL.json. ASSISTANT_EVAL_HELDOUT=1 also runs the held-out set and writes
// EVAL_HELDOUT.md — reported as it is, it does not fail the run.
import { mkdirSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { afterAll, beforeAll, expect, it } from 'vitest'
import { HELDOUT } from '../eval/heldout-cases'
import { CASES, type EvalCase } from '../eval/mongolian-cases'
import { lastMeta, startChat } from './chat-helpers'
import { createTestDb, type TestDb } from './helpers'

let db: TestDb
let cleanup: () => Promise<void>
beforeAll(async () => {
  delete process.env.OPENAI_API_KEY
  ;({ db, cleanup } = await createTestDb())
})
afterAll(() => cleanup())

interface Result {
  id: string
  category: string
  question: string
  pass: boolean
  problems: string[]
  reply: string
}

async function run(c: EvalCase): Promise<Result> {
  const chat = startChat(db)
  let reply = ''
  for (const turn of c.turns) reply = (await chat.say(turn.text, { pageSlug: turn.page ?? null }))?.text ?? ''
  const meta = chat.conversationId ? await lastMeta(db, chat.conversationId) : {}
  const e = c.expect
  const problems: string[] = []
  for (const s of e.contains ?? []) if (!reply.includes(s)) problems.push(`missing «${s}»`)
  if (e.any && !e.any.some((s) => reply.includes(s))) problems.push(`none of ${e.any.map((s) => `«${s}»`).join(', ')}`)
  for (const s of e.not ?? []) if (reply.includes(s)) problems.push(`should not contain «${s}»`)
  if (e.match && !e.match.test(reply)) problems.push(`does not match ${e.match}`)
  const intents = e.intent ? (Array.isArray(e.intent) ? e.intent : [e.intent]) : null
  if (intents && !intents.includes(meta.intent ?? '')) problems.push(`intent ${meta.intent}, expected ${intents.join('/')}`)
  if (e.notIntent && meta.intent === e.notIntent) problems.push(`intent should not be ${e.notIntent}`)
  if (e.event && !(meta.events ?? []).includes(e.event)) problems.push(`event ${e.event} missing (${(meta.events ?? []).join(',')})`)
  if (e.handoff && !(meta.events ?? []).includes(`handover:${e.handoff}`)) problems.push(`no hand-over ${e.handoff}`)
  return { id: c.id, category: c.category, question: c.turns.map((t) => t.text).join(' → '), pass: problems.length === 0, problems, reply }
}

const cell = (s: string) => s.replace(/\|/g, '/').replace(/\n/g, ' ')

function writeReport(file: string, title: string, note: string, results: Result[]) {
  const byCategory = new Map<string, { pass: number; total: number }>()
  for (const r of results) {
    const row = byCategory.get(r.category) ?? { pass: 0, total: 0 }
    row.total++
    if (r.pass) row.pass++
    byCategory.set(r.category, row)
  }
  const dir = path.join(process.cwd(), 'docs', 'assistant')
  mkdirSync(dir, { recursive: true })
  const passed = results.filter((r) => r.pass).length
  const lines = [
    `# ${title}`,
    '',
    note,
    '',
    `**${passed} / ${results.length} passed.**`,
    '',
    '| Category | Passed |',
    '| --- | --- |',
    ...[...byCategory.entries()].map(([k, v]) => `| ${k} | ${v.pass} / ${v.total} |`),
    '',
    '| Case | Conversation | Result |',
    '| --- | --- | --- |',
    ...results.map((r) => `| ${r.id} | ${cell(r.question)} | ${r.pass ? 'pass' : `FAIL: ${cell(r.problems.join('; '))}`} |`),
    '',
  ]
  const failed = results.filter((r) => !r.pass)
  if (failed.length) {
    lines.push('## Replies of the failed cases', '')
    for (const r of failed) lines.push(`### ${r.id}`, '', '```', r.reply, '```', '')
  }
  writeFileSync(path.join(dir, `${file}.md`), lines.join('\n'), 'utf8')
  writeFileSync(path.join(dir, `${file}.json`), JSON.stringify({ passed, total: results.length, byCategory: Object.fromEntries(byCategory), results }, null, 2), 'utf8')
}

it(`Mongolian evaluation (${CASES.length} conversations)`, async () => {
  const results: Result[] = []
  for (const c of CASES) results.push(await run(c))
  if (process.env.ASSISTANT_EVAL_REPORT === '1') {
    writeReport(
      'EVAL',
      'Mongolian evaluation — catalogue mode',
      'Generated by `ASSISTANT_EVAL_REPORT=1 npx vitest run tests/integration/assistant-eval.test.ts` against a fresh seeded test database (no AI model). Cases: `tests/eval/mongolian-cases.ts`. The engine was tuned against this set; EVAL_HELDOUT.md has the untuned score.',
      results,
    )
  }
  const failures = results.filter((r) => !r.pass)
  expect(failures.map((f) => `${f.id}: ${f.problems.join('; ')}\n   ${f.reply.slice(0, 300).replace(/\n/g, ' ⏎ ')}`), 'failed cases').toEqual([])
}, 180_000)

it.runIf(process.env.ASSISTANT_EVAL_HELDOUT === '1')(`held-out set (${HELDOUT.length} conversations, reported as it is)`, async () => {
  const results: Result[] = []
  for (const c of HELDOUT) results.push(await run(c))
  writeReport(
    'EVAL_HELDOUT',
    'Held-out Mongolian evaluation — catalogue mode',
    'Written after the engine was tuned on the main set and run without tuning against it (`ASSISTANT_EVAL_HELDOUT=1`). Cases: `tests/eval/heldout-cases.ts`. Misses are reported as they are.',
    results,
  )
}, 180_000)
